import assert from 'node:assert/strict';
import { sweepTrend, sweepTrendCsv, trendCoordinate, defaultTrendFrequency, trendSequences } from '../src/runner/sweepTrend.ts';
const band = (f, s = -20) => ({ f_center_ghz: f, s11_min_db: s, f_lo_ghz: f - .05, f_hi_ghz: f + .05 });
const job = (x, y = 10, changes = {}) => ({ id: `j-${x}-${y}`, status: 'done', stats: { bands: [band(2 + .1 * x), band(5)],
  farfield: [{ f_ghz: 5, dmax_dbi: 99, rad_efficiency: .1 }, { f_ghz: 2 + .1 * x + .01, dmax_dbi: 3 + x, rad_efficiency: .8 }] },
  sweep: { index: x, sequence_index: 0, sequence_name: 'A', values: { length: x, width: y }, axes: [{ key: 'length', values: [1, 2, 3, 4] }, { key: 'width', values: [10, 20] }] }, ...changes });
const jobs = [job(1), job(2), job(3, 10, { status: 'failed' }), job(4), job(1, 20), job(2, 20), job(4, 20)];
jobs[1].stats.bands.reverse();
let data = sweepTrend(jobs, 0, 'frequency', 2.1, 500);
assert.equal(data.error, null);
assert.deepEqual(data.series.map(s => s.second), [10, 20]);
assert.deepEqual(data.series[0].points.map(p => p.value), [2.1, 2.2, null, 2.4]);
assert.ok(Math.abs(data.series[0].points[1].slope - .1) < 1e-12);
assert.equal(data.series[0].points[3].slope, null, 'never differentiate across a failed point');
assert.equal(data.series[1].points[2].reason, 'missing', 'axes preserve an entirely missing job');
assert.equal(data.series[1].points[3].slope, null);
assert.equal(defaultTrendFrequency([...jobs].reverse()), 2.1);
assert.deepEqual(trendSequences(jobs), [[0, 'A']]);
const gap = structuredClone(jobs); gap[1].stats.bands = [band(5)];
assert.equal(sweepTrend(gap, 0, 'frequency', 2.1, 500).series[0].points[1].reason, 'band', 'lost band does not jump to remote mode');
gap[1].stats.bands = [band(2), band(2.2)];
assert.equal(sweepTrend(gap, 0, 'frequency', 2.1, 500).series[0].points[1].reason, 'band', 'equidistant modes are ambiguous');
for (const status of ['queued', 'running', 'cancelled', 'interrupted', 'failed']) {
  const rows = sweepTrend([job(1, 10, { status })], 0, 's11', 2.1, 500).series[0].points;
  assert.equal(rows[0].value, null, `${status} stats never count as completed`);
}
assert.equal(sweepTrend([...jobs, job(1)], 0, 'frequency', 2.1, 500).series[0].points[0].reason, 'duplicate');
assert.equal(trendCoordinate(.30000000000000004), .3);
const rounded = job(.30000000000000004); rounded.sweep.axes[0].values = [.3];
assert.equal(sweepTrend([rounded], 0, 'frequency', 2.1, 500).series[0].points.length, 1);
assert.equal(sweepTrend([job(1), job(1.00000000001)], 0, 'frequency', 2.1, 500).series[0].points[0].reason, 'duplicate');
const other = job(1); other.sweep.sequence_index = 1; other.stats.bands = [band(4)];
assert.equal(sweepTrend([...jobs, other], 1, 'frequency', 4, 200).series[0].points[0].value, 4, 'sequences never mix');
const malformed = job(1); malformed.sweep.values.length = NaN;
assert.equal(sweepTrend([malformed], 0, 'frequency', 2, 100).error, 'axes');
for (const [ref, radius] of [[0, 1], [NaN, 1], [1, Infinity], [1, 0], [1, -1]]) assert.equal(sweepTrend(jobs, 0, 'frequency', ref, radius).error, 'settings');
const close = (a,b) => assert.ok(Math.abs(a-b) < 1e-10, `${a} != ${b}`);
close(sweepTrend(jobs, 0, 'bandwidth', 2.1, 500).series[0].points[0].value, 100);
assert.equal(sweepTrend(jobs, 0, 's11', 2.1, 500).series[0].points[0].value, -20);
data = sweepTrend(jobs, 0, 'directivity', 2.1, 500);
assert.equal(data.series[0].points[0].value, 4, 'field selected by frequency, not first index');
close(data.series[0].points[0].fieldGHz, 2.11);
const absent = job(1); delete absent.stats.bands[0].f_hi_ghz;
assert.equal(sweepTrend([absent], 0, 'bandwidth', 2.1, 500).series[0].points[0].value, null);
absent.stats.farfield = [{ f_ghz: 9, dmax_dbi: 50 }];
assert.equal(sweepTrend([absent], 0, 'directivity', 2.1, 500).series[0].points[0].reason, 'field');
const raw = job(1); raw.stats.farfield[1].rad_efficiency = 1.2;
const point = sweepTrend([raw], 0, 'efficiency', 2.1, 500).series[0].points[0];
assert.equal(point.value, 120); assert.equal(point.nonphysical, true);
raw.stats.farfield[1].rad_efficiency = -.1;
assert.equal(sweepTrend([raw], 0, 'efficiency', 2.1, 500).series[0].points[0].nonphysical, true);
raw.stats.farfield[1].rad_efficiency = NaN;
assert.equal(sweepTrend([raw], 0, 'efficiency', 2.1, 500).series[0].points[0].reason, 'metric');
const csv = sweepTrendCsv(data, 'directivity', 0, 2.1, 500);
assert.equal(csv.split('\r\n').length, 10, 'header, eight expected grid coordinates and trailing newline');
assert.ok(csv.includes('j-1-10,done,directivity,dBi,4,,2.1,2.11,ok,,false,2.1,500'));
assert.ok(csv.includes('j-3-10,failed,directivity,dBi,,,,,unfinished'));
const textData = structuredClone(data); textData.first = '=HYPERLINK("x")';
assert.ok(sweepTrendCsv(textData, 'frequency', 0, 2, 50).includes('"\'=HYPERLINK(""x"")"'), 'untrusted identifiers cannot become spreadsheet formulas');
console.log('Sweep trend: reordered/lost/ambiguous bands, terminal gaps, missing grid points, rounded/duplicate coordinates, sequence isolation, five metrics, field provenance, slopes and CSV passed. Synthetic contracts only.');
