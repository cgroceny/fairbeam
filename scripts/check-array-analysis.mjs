// T3(beta*cos u) = beta^3*cos(3u) + (3beta^3-3beta)*cos u.
const beta = Math.cosh(Math.acosh(10 ** (30 / 20)) / 3), edge = beta * beta / (3 * (beta * beta - 1));
admitted(taperAmplitudes(4, 'chebyshev', 30)).forEach((x, i) => near(x, [edge, 1, 1, edge][i]));
// T4 gives a separate odd-length, closed-form polynomial control.
const beta4 = Math.cosh(Math.acosh(10 ** (30 / 20)) / 4), mid = 3 * beta4 ** 4 - 4 * beta4 ** 2 + 1;
const c5 = [.5 * beta4 ** 4, 2 * beta4 ** 4 - 2 * beta4 ** 2, mid, 2 * beta4 ** 4 - 2 * beta4 ** 2, .5 * beta4 ** 4].map(x => x / mid);
admitted(taperAmplitudes(5, 'chebyshev', 30)).forEach((x, i) => near(x, c5[i]));
admitted(taperAmplitudes(5, 'binomial')).forEach((x, i) => near(x, [1 / 6, 4 / 6, 1, 4 / 6, 1 / 6][i]));
for (const count of [2, 3, 5, 8, 32, 64]) for (const kind of ['uniform', 'binomial', 'chebyshev', 'taylor']) {
  const w = admitted(taperAmplitudes(count, kind, 60));
  near(Math.max(...w), 1); w.forEach((x, i) => { check(x > 0 && Number.isFinite(x), 'positive finite window'); near(x, w[count - i - 1], 1e-10); });
}
for (const args of [[1, 'taylor'], [65, 'uniform'], [4.5, 'binomial'], [8, 'bad'], [8, 'chebyshev', 61], [8, 'taylor', NaN]]) refused(taperAmplitudes(...args), 'range');

const port = (number, x, y = 0, z = 0) => ({ number, start: [x, y, z], stop: [x, y, z], excite: true, R: 50 });
