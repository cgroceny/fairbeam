let checks = 0;
const check = (condition, message) => { checks++; assert.ok(condition, message); };
const near = (a, b, tolerance = 1e-10) => check(Math.abs(a - b) <= tolerance, `${a} != ${b} (tolerance ${tolerance})`);
const admitted = result => { check(result.ok, `admission: ${JSON.stringify(result)}`); return result.value; };
const refused = (result, reason) => { check(!result.ok, 'must refuse'); if (reason) check(result.reason === reason, `${result.reason} != ${reason}`); };

